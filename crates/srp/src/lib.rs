//! `srp` —— 基于 SSH 的弹性 TCP 代理。
//!
//! # 设计目标
//!
//! 1. **无需改动 SSH 服务端**：默认模式只使用标准 `direct-tcpip` 通道，
//!    任何未经修改的 sshd 都能作为出口。
//! 2. **保持连接**：主动 SSH 保活穿透 NAT 与状态防火墙，让死链在数十秒内
//!    暴露，而不是等到用户请求失败时才发现。
//! 3. **断网自愈**：会话失效后按带抖动的指数退避自动重连；断网期间新到达
//!    的代理请求排队等待而非立即报错。
//! 4. **掉包恢复**：分两个层级——
//!    - `direct-tcpip` 模式：请求级重放（通道打开阶段的失败对调用方透明）；
//!    - `helper` 模式：字节级续传，靠带确认序号的重传缓冲，重连期间零字节丢失。
//!
//! # 模块结构
//!
//! * [`frontend`]：入口协议（SOCKS5 / HTTP CONNECT），只认识入口协议，
//!   通过 [`frontend::Dialer`] 与隧道解耦；
//! * [`tunnel`]：SSH 会话生命周期、自愈监督、两种模式的 Dialer 实现；
//! * [`app`]：把三者接线成一个可运行的代理。

